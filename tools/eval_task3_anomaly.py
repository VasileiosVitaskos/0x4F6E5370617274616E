def get_worker_modules(spartan_repo):
    global _WORKER_MODS
    if _WORKER_MODS is None:
        spartan_cls = load_spartan_class(spartan_repo)
        if spartan_repo not in sys.path:
            sys.path.insert(0, spartan_repo)
        from benchmark.anomaly_detection.knn import KNN
        from benchmark.anomaly_detection.evaluation.basic_metrics import (
            basic_metricor,
            generate_curve,
        )
        from benchmark.anomaly_detection.evaluation.affiliation.generics import (
            convert_vector_to_events,
        )
        from benchmark.anomaly_detection.evaluation.affiliation.metrics import (
            pr_from_events,
        )

        def fast_get_metrics(score, labels, slidingWindow=100):
            grader = basic_metricor()
            auc_roc, *_ = grader.metric_new(labels, score, None, plot_ROC=False)
            _, _, auc_pr = grader.metric_PR(labels, score)
            # the Python generate_curve, as their get_metrics (metrics.py:29);
            # the numba one extends the labels differently and gives other values
            _, _, _, _, _, _, vus_roc, vus_pr = generate_curve(
                labels, score, 2 * slidingWindow
            )
            discrete_score = np.array(score > 0.5, dtype=np.float32)
            events_pred = convert_vector_to_events(discrete_score)
            events_gt = convert_vector_to_events(labels)
            aff = pr_from_events(events_pred, events_gt, (0, len(discrete_score)))
            ap = aff["Affiliation_Precision"]
            ar = aff["Affiliation_Recall"]
            aff_f = 2.0 * ap * ar / (ap + ar + 1e-5)
            return {
                "VUS-PR": float(vus_pr),
                "VUS-ROC": float(vus_roc),
                "AUC-PR": float(auc_pr),
                "AUC-ROC": float(auc_roc),
                "Affiliation-F": float(aff_f),
            }

        _WORKER_MODS = (spartan_cls, KNN, fast_get_metrics)
    return _WORKER_MODS


def discover_tsb_files(tsb_dir, collections=None, max_per_folder=0, max_len=300000):
    cols = collections if collections else AD_COLLECTIONS_FULL
    items = []
    for col in cols:
        cdir = os.path.join(tsb_dir, col)
        if not os.path.isdir(cdir):
            continue
        files = sorted(
            f
            for f in os.listdir(cdir)
            if f.endswith(".out") and not f.endswith(".train.out")
        )
        kept = 0
        for fn in files:
            fpath = os.path.join(cdir, fn)
            try:
                with open(fpath, "rb") as bf:
                    n_lines = sum(1 for _ in bf)
                if n_lines < 250 or n_lines > max_len:
                    continue
            except OSError:
                continue
            items.append((col, fn, fpath))
            kept += 1
            if max_per_folder > 0 and kept >= max_per_folder:
                break
    return items


