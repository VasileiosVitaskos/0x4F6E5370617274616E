def summarize_ad_tag(block, tag, s, rows):
    ok = [r for r in rows if not r.get("error") and r.get("vus_pr_online") != ""]
    if not ok:
        return dict(block=block, tag=tag, n_series=0)

    def arr(k):
        a = np.array([float(r[k]) for r in ok], dtype=float)
        return np.nan_to_num(a, nan=0.0)

    def wtl_p(a, b):
        w = int(np.sum(a > b + 1e-12))
        t = int(np.sum(np.abs(a - b) <= 1e-12))
        l = int(np.sum(a < b - 1e-12))
        if np.all(np.abs(a - b) <= 1e-12):
            p = 1.0
        else:
            try:
                _, p = wilcoxon(a, b, zero_method="zsplit")
            except Exception:
                p = 1.0
        return w, t, l, float(p)

    vpr_on, vpr_st, vpr_ba = (
        arr("vus_pr_online"),
        arr("vus_pr_static"),
        arr("vus_pr_batch"),
    )
    vroc_on, vroc_st, vroc_ba = (
        arr("vus_roc_online"),
        arr("vus_roc_static"),
        arr("vus_roc_batch"),
    )
    apr_on, apr_st, apr_ba = (
        arr("auc_pr_online"),
        arr("auc_pr_static"),
        arr("auc_pr_batch"),
    )
    aroc_on, aroc_st, aroc_ba = (
        arr("auc_roc_online"),
        arr("auc_roc_static"),
        arr("auc_roc_batch"),
    )
    aff_on, aff_st, aff_ba = (
        arr("aff_f_online"),
        arr("aff_f_static"),
        arr("aff_f_batch"),
    )

    w_on, t_on, l_on, p_on = wtl_p(vpr_on, vpr_ba)
    w_st, t_st, l_st, p_st = wtl_p(vpr_st, vpr_ba)
    w_lo, t_lo, l_lo, p_lo = wtl_p(vpr_st, vpr_on)

    return dict(
        block=block,
        tag=tag,
        n_series=len(ok),
        stride=s["stride"],
        k=s["k"],
        total_bits=s["total_bits"],
        lam=s["lam"],
        theta=s["theta"],
        warmup_cap=s["warmup_cap"],
        mean_t1=float(arr("t1").mean()),
        mean_t2=float(arr("t2").mean()),
        vus_pr_online=float(vpr_on.mean()),
        vus_pr_static=float(vpr_st.mean()),
        vus_pr_batch=float(vpr_ba.mean()),
        wtl_vus_pr_online=f"{w_on}/{t_on}/{l_on}",
        p_vus_pr_online=p_on,
        wtl_vus_pr_static=f"{w_st}/{t_st}/{l_st}",
        p_vus_pr_static=p_st,
        wtl_st_vs_on=f"{w_lo}/{t_lo}/{l_lo}",
        p_st_vs_on=p_lo,
        vus_roc_online=float(vroc_on.mean()),
        vus_roc_static=float(vroc_st.mean()),
        vus_roc_batch=float(vroc_ba.mean()),
        auc_pr_online=float(apr_on.mean()),
        auc_pr_static=float(apr_st.mean()),
        auc_pr_batch=float(apr_ba.mean()),
        auc_roc_online=float(aroc_on.mean()),
        auc_roc_static=float(aroc_st.mean()),
        auc_roc_batch=float(aroc_ba.mean()),
        aff_f_online=float(aff_on.mean()),
        aff_f_static=float(aff_st.mean()),
        aff_f_batch=float(aff_ba.mean()),
        sec_online_mean=float(arr("sec_online").mean()),
        sec_static_mean=float(arr("sec_static").mean()),
        sec_batch_mean=float(arr("sec_batch").mean()),
        total_recut_mismatch=int(arr("recut_mismatch").sum()),
    )


def build_ad_sweep_configs(blocks):
    plan = []
    if "base" in blocks or "all" in blocks:
        plan.append(("base", "base_s25_a16_w16_lam0.5_th45", dict(BASE_AD_CFG)))
    if "stride" in blocks or "all" in blocks:
        for st in SWEEP_AD_STRIDE:
            if st != BASE_AD_CFG["stride"]:
                plan.append(
                    ("stride", f"stride_{st}", dict(BASE_AD_CFG, stride=int(st)))
                )
    if "alpha" in blocks or "all" in blocks:
        for a in SWEEP_AD_ALPHA:
            bits_per_sym = int(round(math.log2(a)))
            tb = BASE_AD_CFG["k"] * bits_per_sym
            if tb != BASE_AD_CFG["total_bits"]:
                plan.append(
                    ("alpha", f"alpha_{a}_bits_{tb}", dict(BASE_AD_CFG, total_bits=tb))
                )
    if "wordlen" in blocks or "all" in blocks:
        for w in SWEEP_AD_WORDLEN:
            if w != BASE_AD_CFG["k"]:
                plan.append(
                    (
                        "wordlen",
                        f"wordlen_{w}_bits_{4*w}",
                        dict(BASE_AD_CFG, k=int(w), total_bits=int(4 * w)),
                    )
                )
    if "lambda" in blocks or "all" in blocks:
        for lam in SWEEP_AD_LAMBDA:
            if abs(lam - BASE_AD_CFG["lam"]) > 1e-9:
                plan.append(
                    ("lambda", f"lambda_{lam:g}", dict(BASE_AD_CFG, lam=float(lam)))
                )
    if "theta" in blocks or "all" in blocks:
        for th in SWEEP_AD_THETA:
            if abs(th - BASE_AD_CFG["theta"]) > 1e-9:
                plan.append(
                    ("theta", f"theta_{int(th)}", dict(BASE_AD_CFG, theta=float(th)))
                )
    if "warmup" in blocks or "all" in blocks:
        for wc in SWEEP_AD_WARMUP:
            if wc != BASE_AD_CFG["warmup_cap"]:
                plan.append(
                    ("warmup", f"warmup_{wc}", dict(BASE_AD_CFG, warmup_cap=int(wc)))
                )
    if "ahead" in blocks:
        for fa in SWEEP_AD_AHEAD:
            plan.append(
                ("ahead", f"ahead_{fa:g}", dict(BASE_AD_CFG, freeze_ahead=float(fa)))
            )
    return plan


def generate_ad_figures(out_dir):
    fig_dir = os.path.join(out_dir, "figures")
    os.makedirs(fig_dir, exist_ok=True)
    base_csv = os.path.join(out_dir, "per_setting", "base_s25_a16_w16_lam0.5_th45.csv")
    if os.path.exists(base_csv):
        rows = [
            r
            for r in csv.DictReader(open(base_csv))
            if not r.get("error") and r.get("vus_pr_online") != ""
        ]
        if rows:
            f = lambda k: np.clip(
                np.nan_to_num(np.array([float(r[k]) for r in rows])), 0.0, 1.0
            )
            plot_pairwise_scatter(
                f("vus_pr_batch"),
                f("vus_pr_online"),
                "Batch SPARTAN (64 bits)",
                "Online SPARTAN (64 bits)",
                "TSB-UAD VUS-PR (Online vs. Batch SPARTAN)",
                os.path.join(fig_dir, "fig9_pairwise_vus_pr_online_vs_batch"),
            )
            plot_pairwise_scatter(
                f("vus_pr_batch"),
                f("vus_pr_static"),
                "Batch SPARTAN (64 bits)",
                "Static SPARTAN (warm-up fit, 64 bits)",
                "TSB-UAD VUS-PR (Static vs. Batch SPARTAN)",
                os.path.join(fig_dir, "fig9_pairwise_vus_pr_static_vs_batch"),
            )
            plot_critical_diagram(
                {
                    "Static (warm-up fit)": f("vus_pr_static"),
                    "Online SPARTAN": f("vus_pr_online"),
                    "Batch SPARTAN": f("vus_pr_batch"),
                },
                "Critical Diagram: TSB-UAD Anomaly Detection (VUS-PR)",
                os.path.join(fig_dir, "fig9_cd_anomaly_vus_pr"),
            )


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tsb-dir", default=DEFAULT_TSB_DIR)
    ap.add_argument("--spartan-repo", default=DEFAULT_SPARTAN_REPO)
    ap.add_argument("--bin", default=DEFAULT_BIN)
    ap.add_argument("--out", default=DEFAULT_OUT_TASK3)
    ap.add_argument("--blocks", default="base")
    ap.add_argument("--collections", nargs="*", default=None)
    ap.add_argument("--max-per-folder", type=int, default=0)
    ap.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    ap.add_argument("--no-resume", action="store_true")
    args = ap.parse_args()

    os.makedirs(os.path.join(args.out, "per_setting"), exist_ok=True)
    sum_path = os.path.join(args.out, "tsb_anomaly_summary.csv")

    items = discover_tsb_files(args.tsb_dir, args.collections, args.max_per_folder)
    if not items:
        sys.exit(f"No .out files found in {args.tsb_dir}")

    blocks = {b.strip().lower() for b in args.blocks.split(",")}
    plan = build_ad_sweep_configs(blocks)
    print(
        f"TSB-UAD Dir : {args.tsb_dir} ({len(items)} time series across {len(set(x[0] for x in items))} collections)"
    )
    print(f"Task-III    : {len(plan)} configurations | Workers: {args.workers}")
    print(f"Output Dir  : {args.out}\n")

    summary_rows = []
    for idx_cfg, (blk, tag, setting) in enumerate(plan, 1):
        t0 = time.perf_counter()
        ds_csv = os.path.join(args.out, "per_setting", f"{tag}.csv")

        done_map = {}
        if not args.no_resume and os.path.exists(ds_csv):
            for r in csv.DictReader(open(ds_csv)):
                if not r.get("error") and r.get("vus_pr_online") != "":
                    done_map[(r["collection"], r["dataset"])] = r

        todo = [
            (col, fname, fpath, tag, setting, args.bin, args.spartan_repo, args.out)
            for (col, fname, fpath) in items
            if (col, fname) not in done_map
        ]

        if not todo:
            per_rows = [done_map[(col, fname)] for (col, fname, _) in items]
            s_row = summarize_ad_tag(blk, tag, setting, per_rows)
            s_row["elapsed_s"] = 0.0
            summary_rows.append(s_row)
            print(
                f"  [{idx_cfg}/{len(plan)}] {tag:<28} | CACHED ({len(items)}) | "
                f"VUS-PR On/St/Ba: {s_row['vus_pr_online']:.4f}/{s_row['vus_pr_static']:.4f}/{s_row['vus_pr_batch']:.4f} | "
                f"WTL(On): {s_row['wtl_vus_pr_online']} (p={s_row['p_vus_pr_online']:.3f}) | "
                f"WTL(St): {s_row['wtl_vus_pr_static']} (p={s_row['p_vus_pr_static']:.3f})"
            )
            continue

        completed = len(done_map)
        with concurrent.futures.ProcessPoolExecutor(max_workers=args.workers) as ex:
            fut_map = {ex.submit(evaluate_one_worker, t): (t[0], t[1]) for t in todo}
            for fut in concurrent.futures.as_completed(fut_map):
                col, fname = fut_map[fut]
                res = fut.result()
                done_map[(col, fname)] = res
                completed += 1
                sys.stdout.write(
                    f"\r  [{idx_cfg}/{len(plan)}] {tag:<26} series {completed:4d}/{len(items)} ({col}/{fname[:22]:<22})"
                )
                sys.stdout.flush()

                if completed % 5 == 0 or completed == len(items):
                    ordered_partial = [
                        done_map[(c, f)] for (c, f, _) in items if (c, f) in done_map
                    ]
                    tmp_csv = f"{ds_csv}.tmp"
                    with open(tmp_csv, "w", newline="") as f:
                        w = csv.DictWriter(f, fieldnames=CSV_COLS_T3, restval="")
                        w.writeheader()
                        w.writerows(ordered_partial)
                    os.replace(tmp_csv, ds_csv)

        per_rows = [
            done_map[(col, fname)]
            for (col, fname, _) in items
            if (col, fname) in done_map
        ]
        s_row = summarize_ad_tag(blk, tag, setting, per_rows)
        s_row["elapsed_s"] = round(time.perf_counter() - t0, 1)
        summary_rows.append(s_row)

        with open(sum_path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(summary_rows[0].keys()), restval="")
            w.writeheader()
            w.writerows(summary_rows)

        print(
            f"\r  [{idx_cfg}/{len(plan)}] {tag:<28} | "
            f"VUS-PR On/St/Ba: {s_row.get('vus_pr_online', 0):.4f}/{s_row.get('vus_pr_static', 0):.4f}/{s_row.get('vus_pr_batch', 0):.4f} | "
            f"WTL(On): {s_row.get('wtl_vus_pr_online', '-')} (p={s_row.get('p_vus_pr_online', 1):.3f}) | "
            f"WTL(St): {s_row.get('wtl_vus_pr_static', '-')} (p={s_row.get('p_vus_pr_static', 1):.3f}) | {s_row['elapsed_s']}s"
        )
        gc.collect()

    generate_ad_figures(args.out)
    print(f"\nDone! Summary table: {sum_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
