def extract_strided_windows(data_1d, win, stride):
    n_samples = len(data_1d)
    starts = np.arange(0, n_samples - win + 1, stride, dtype=np.int64)
    idx = starts[:, None] + np.arange(win, dtype=np.int64)[None, :]
    return data_1d[idx], starts


def load_online_words(run_dir, k, X_win, warmup):
    """The C's words, the epoch that wrote each, and every epoch's basis and
    dictionary. Row i of words is strided window i (words.csv numbers the
    windows after the warm-up prefix, so window warmup + i). Every word is cut
    again here from X_win through its own epoch and must agree; a letter whose
    projection lies on a cut point (rounding) is not counted.
    Returns (words, ep, eps, recut_mismatch).
    """
    epochs = read_epochs(run_dir)
    eps = []
    for e in range(len(epochs)):
        ev, bits, alpha, bkpt = read_our_dict(os.path.join(run_dir, f"dict_{e}.csv"), k)
        eps.append(
            dict(
                alpha=alpha,
                bkpt=bkpt,
                basis=read_our_basis(os.path.join(run_dir, f"basis_{e}.csv")),
            )
        )
    widx, words = read_words(os.path.join(run_dir, "words.csv"))
    widx = np.asarray(widx)
    if len(words) != len(X_win):
        raise RuntimeError(f"C wrote {len(words)} words for {len(X_win)} windows")
    firsts = np.array([e["first"] for e in epochs])
    ep = np.searchsorted(firsts, widx, side="right") - 1
    mism = 0
    for e in np.unique(ep):
        ix = np.flatnonzero(ep == e)
        mism += recut_check(
            X_win[ix] @ eps[e]["basis"].T, words[ix], eps[e]["bkpt"], eps[e]["alpha"]
        )
    return words, ep, eps, mism


def kth_distances(word_of, ep, n_epochs, k_nn):
    """Distance from every window to its k_nn-th nearest OTHER window, L1 on
    the letters, a pair compared in the OLDER of its two epochs (search form).

    word_of(e, idx): words of windows idx (all of epoch >= e) in epoch e's
    dictionary, the stored word for epoch e itself, the window cut again for
    a later one. For every epoch e with members S and later windows L:
      tree on S, asked by S (k+1, the window's own 0 dropped) and by L
      tree on L (in e's letters), asked by S
    so every pair is seen from both ends. Each window keeps its k_nn smallest
    distances; the k-th of a multiset does not depend on how ties are broken,
    so this is what their KNN (sklearn, self excluded) returns.
    """
    from sklearn.neighbors import NearestNeighbors

    n = len(ep)
    best = np.full((n, k_nn), np.inf)

    def merge(rows, d):
        if d.shape[1] < k_nn:
            d = np.hstack([d, np.full((d.shape[0], k_nn - d.shape[1]), np.inf)])
        best[rows] = np.partition(np.hstack([best[rows], d]), k_nn - 1, axis=1)[
            :, :k_nn
        ]

    for e in range(n_epochs):
        S = np.flatnonzero(ep == e)
        L = np.flatnonzero(ep > e)
        if len(S) == 0:
            continue
        WS = word_of(e, S)
        tree = NearestNeighbors(metric="l1").fit(WS)
        kk = min(k_nn + 1, len(S))
        d, _ = tree.kneighbors(WS, n_neighbors=kk)
        merge(S, d[:, 1:])  # ascending: column 0 is the window's own 0
        if len(L):
            WL = word_of(e, L)
            d, _ = tree.kneighbors(WL, n_neighbors=min(k_nn, len(S)))
            merge(L, d)
            d, _ = (
                NearestNeighbors(metric="l1")
                .fit(WL)
                .kneighbors(WS, n_neighbors=min(k_nn, len(L)))
            )
            merge(S, d)
    return best.max(axis=1)


def window_scores_to_point_scores(win_scores, starts, win, n_samples):
    """The second half of knn_window_scores_to_point_scores, unchanged."""
    centers = np.clip(starts + (win // 2), 0, n_samples - 1).astype(np.float64)
    t_grid = np.arange(n_samples, dtype=np.float64)
    point_scores = np.interp(t_grid, centers, win_scores)
    return (
        MinMaxScaler(feature_range=(0, 1))
        .fit_transform(point_scores.reshape(-1, 1))
        .ravel()
    )


def knn_window_scores_to_point_scores(
    knn_cls, symbol_words, starts, win, n_samples, n_neighbors=50
):
    k_eff = min(n_neighbors, max(1, symbol_words.shape[0] - 1))
    clf = knn_cls(n_neighbors=k_eff, method="largest", n_jobs=1, metric="l1")
    clf.fit(symbol_words)
    win_scores = np.asarray(clf.decision_scores_, dtype=np.float64).ravel()

    centers = np.clip(starts + (win // 2), 0, n_samples - 1).astype(np.float64)
    t_grid = np.arange(n_samples, dtype=np.float64)
    point_scores = np.interp(t_grid, centers, win_scores)
    point_scores = (
        MinMaxScaler(feature_range=(0, 1))
        .fit_transform(point_scores.reshape(-1, 1))
        .ravel()
    )
    return point_scores


def run_c_on_strided_windows(bin_path, X_win_raw, setting, run_dir, frames_path):
    n_win, win = X_win_raw.shape
    k = setting["k"]
    warmup = min(setting["warmup_cap"], max(k + 4, n_win // 2))
    ring_w = max(k + 4, warmup)

    if not os.path.exists(frames_path) or os.path.getsize(frames_path) == 0:
        if warmup <= n_win:
            W_pre = X_win_raw[:warmup]
        else:
            reps = (warmup // n_win) + 1
            W_pre = np.tile(X_win_raw, (reps, 1))[:warmup]
        all_rows = np.vstack([W_pre, X_win_raw])
        tmp_f = f"{frames_path}.tmp.{os.getpid()}"
        np.savetxt(tmp_f, all_rows.reshape(-1), fmt="%.17g")
        os.replace(tmp_f, frames_path)

    os.makedirs(run_dir, exist_ok=True)
    for fn in os.listdir(run_dir):
        if fn.startswith(("dict_", "basis_", "epochs", "words", "settings")):
            try:
                os.remove(os.path.join(run_dir, fn))
            except OSError:
                pass

    cfg_path = os.path.join(run_dir, "run.cfg")
    words_path = os.path.join(run_dir, "words.csv")
    with open(cfg_path, "w") as f:
        f.write(f"input               = {frames_path}\n")
        f.write("channels            = 1\n")
        f.write(f"window              = {win}\n")
        f.write(f"stride              = {win}\n")
        f.write(f"components          = {k}\n")
        f.write(f"total_bits          = {setting['total_bits']}\n")
        f.write(f"lambda              = {setting['lam']}\n")
        f.write(f"step                = {setting['step']}\n")
        f.write(f"basis_average       = {setting['beta']}\n")
        f.write(f"gs_period           = {setting['gs_period']}\n")
        f.write(f"angle_period        = {setting['gs_period']}\n")
        f.write(f"theta_threshold_deg = {setting['theta']}\n")
        f.write(f"warmup              = {warmup}\n")
        f.write(f"ring_window         = {ring_w}\n")
        f.write(f"freeze_ahead        = {setting['freeze_ahead']}\n")
        f.write(
            "window_znorm        = false\n"
        )  # raw windows: level and amplitude stay
        f.write(f"out_dir             = {run_dir}\n")
        f.write(f"words               = {words_path}\n")

    t0 = time.perf_counter()
    p = subprocess.run([bin_path, cfg_path], capture_output=True, text=True)
    elapsed = time.perf_counter() - t0
    if p.returncode != 0:
        raise RuntimeError(f"C exit {p.returncode}: {p.stderr.strip()[:200]}")

    words, ep, eps, recut_mismatch = load_online_words(run_dir, k, X_win_raw, warmup)

    t1_cnt, t2_cnt = 0, 0
    ep_path = os.path.join(run_dir, "epochs.csv")
    if os.path.exists(ep_path):
        for r in csv.DictReader(open(ep_path)):
            tp = int(r["type"])
            if tp == 1:
                t1_cnt += 1
            elif tp == 2:
                t2_cnt += 1

    for fn in os.listdir(run_dir):
        if fn.startswith(("dict_", "basis_", "epochs", "words", "settings")):
            try:
                os.remove(os.path.join(run_dir, fn))
            except OSError:
                pass

    return words, ep, eps, recut_mismatch, warmup, t1_cnt, t2_cnt, elapsed


def run_batch_on_strided_windows(spartan_cls, X_win_raw, setting):
    n_win, win = X_win_raw.shape
    k = setting["k"]
    alpha_in = 2 ** (setting["total_bits"] // k)
    t0 = time.perf_counter()
    sp = spartan_cls(
        alphabet_size=alpha_in,
        window_size=win,
        word_length=k,
        binning_method="equi-depth",
        remove_repeat_words=False,
        build_histogram=False,
        bit_budget=setting["total_bits"],
        assignment_policy="DAA",
        lamda=setting["lam"],
    )
    words = sp.fit_transform(X_win_raw)
    if words.ndim == 3:
        words = words[:, 0, :]
    elapsed = time.perf_counter() - t0
    return np.asarray(words, dtype=np.float64), elapsed


def run_static_on_strided_windows(spartan_cls, X_win_raw, setting, warmup):
    """Their SPARTAN, same parameters as the batch column, fitted on the first
    `warmup` windows only (the online method's warm-up) and then frozen."""
    n_win, win = X_win_raw.shape
    k = setting["k"]
    alpha_in = 2 ** (setting["total_bits"] // k)
    t0 = time.perf_counter()
    sp = spartan_cls(
        alphabet_size=alpha_in,
        window_size=win,
        word_length=k,
        binning_method="equi-depth",
        remove_repeat_words=False,
        build_histogram=False,
        bit_budget=setting["total_bits"],
        assignment_policy="DAA",
        lamda=setting["lam"],
    )
    sp.fit(X_win_raw[:warmup])
    words = sp.transform(X_win_raw)
    if words.ndim == 3:
        words = words[:, 0, :]
    elapsed = time.perf_counter() - t0
    return np.asarray(words, dtype=np.float64), elapsed


def evaluate_one_worker(task_args):
    col, fname, fpath, tag, setting, bin_path, spartan_repo, work_dir = task_args
    try:
        spartan_cls, knn_cls, get_metrics_fn = get_worker_modules(spartan_repo)

        df = pd.read_csv(fpath).dropna()
        data_raw = df.iloc[:, 0:-1].values.astype(float).reshape(-1)
        label = df.iloc[:, -1].astype(int).to_numpy()

        win = setting["window"]
        stride = setting["stride"]
        k = setting["k"]
        if (
            len(data_raw) < win + stride * (k + 6)
            or np.sum(label > 0) == 0
            or np.all(label > 0)
        ):
            return dict(
                collection=col, dataset=fname, error="invalid length or trivial labels"
            )

        std_val = np.std(data_raw)
        if std_val < 1e-12:
            return dict(collection=col, dataset=fname, error="constant series")
        data = (data_raw - np.mean(data_raw)) / std_val
        n_samples = len(data)

        X_win_raw, starts = extract_strided_windows(data, win, stride)
        n_win = X_win_raw.shape[0]
        if n_win < k + 6:
            return dict(collection=col, dataset=fname, error="too few strided windows")

        safe_id = f"{col}__{fname.replace('.out', '')}"
        run_dir = os.path.join(work_dir, "runs", f"{tag}__{safe_id}")
        frames_dir = os.path.join(work_dir, "_frames_cache")
        batch_cache_dir = os.path.join(work_dir, "_batch_strided_cache")
        os.makedirs(frames_dir, exist_ok=True)
        os.makedirs(batch_cache_dir, exist_ok=True)

        warmup = min(setting["warmup_cap"], max(k + 4, n_win // 2))
        frames_path = os.path.join(
            frames_dir, f"{safe_id}_win{win}_s{stride}_w{warmup}.frames"
        )

        # 1. Online SPARTAN: the C on the RAW windows (data_raw, nothing
        # normalised with future data; the letters do not change under a
        # shift or scale of the series, make affine)
        X_win_c, _ = extract_strided_windows(data_raw, win, stride)
        frames_path = frames_path.replace(".frames", "_raw.frames")
        words_on, ep_on, eps_on, recut_mismatch, warmup_used, t1, t2, sec_on = (
            run_c_on_strided_windows(bin_path, X_win_c, setting, run_dir, frames_path)
        )
        if recut_mismatch:
            raise RuntimeError(
                f"recut check: {recut_mismatch} letters differ from the C"
            )
        words_on = words_on.astype(np.int64)

        def word_of(e, idx):
            out = words_on[idx].copy()
            later = ep_on[idx] != e
            if later.any():
                E = eps_on[e]
                out[later] = digitize(
                    X_win_c[idx[later]] @ E["basis"].T, E["bkpt"], E["alpha"]
                )
            return out

        k_eff = min(50, max(1, n_win - 1))
        t0 = time.perf_counter()
        kth_on = kth_distances(word_of, ep_on, len(eps_on), k_eff)
        sec_on += time.perf_counter() - t0
        score_on = window_scores_to_point_scores(kth_on, starts, win, n_samples)
        m_on = get_metrics_fn(score_on, label, slidingWindow=win)

        # 2. Static: their SPARTAN fitted on the same warm-up windows, frozen
        words_st, sec_st = run_static_on_strided_windows(
            spartan_cls, X_win_raw, setting, warmup_used
        )
        score_st = knn_window_scores_to_point_scores(
            knn_cls, words_st, starts, win, n_samples
        )
        m_st = get_metrics_fn(score_st, label, slidingWindow=win)

        try:
            os.rmdir(run_dir)
        except OSError:
            pass

        # 3. Classic Batch SPARTAN
        b_key = f"{safe_id}__w{win}_s{stride}_k{k}_b{setting['total_bits']}_lam{setting['lam']:g}_pyvus.json"
        b_cache_path = os.path.join(batch_cache_dir, b_key)
        m_ba = None
        sec_ba = 0.0
        if os.path.exists(b_cache_path):
            try:
                cached = json.load(open(b_cache_path))
                m_ba = cached["metrics"]
                sec_ba = cached["sec_batch"]
            except Exception:
                m_ba = None

        if m_ba is None:
            words_ba, sec_ba = run_batch_on_strided_windows(
                spartan_cls, X_win_raw, setting
            )
            score_ba = knn_window_scores_to_point_scores(
                knn_cls, words_ba, starts, win, n_samples
            )
            m_ba = get_metrics_fn(score_ba, label, slidingWindow=win)
            # our epoch-aware KNN, one epoch, on the batch words: must be theirs
            wb = words_ba.astype(np.int64)
            kth_theirs = (
                knn_cls(n_neighbors=k_eff, method="largest", n_jobs=1, metric="l1")
                .fit(wb)
                .decision_scores_
            )
            kth_ours = kth_distances(
                lambda e, idx: wb[idx], np.zeros(n_win, dtype=int), 1, k_eff
            )
            diff = float(np.max(np.abs(np.asarray(kth_theirs) - kth_ours)))
            if diff > 1e-9:
                raise RuntimeError(
                    f"self check: our KNN differs from theirs by {diff:g}"
                )
            tmp_b = f"{b_cache_path}.tmp.{os.getpid()}"
            with open(tmp_b, "w") as bf:
                json.dump({"metrics": m_ba, "sec_batch": sec_ba}, bf)
            os.replace(tmp_b, b_cache_path)

        return dict(
            collection=col,
            dataset=fname,
            length=n_samples,
            n_windows=n_win,
            stride=stride,
            warmup=warmup_used,
            t1=t1,
            t2=t2,
            vus_pr_online=float(m_on.get("VUS-PR", 0.0)),
            vus_pr_static=float(m_st.get("VUS-PR", 0.0)),
            vus_pr_batch=float(m_ba.get("VUS-PR", 0.0)),
            vus_roc_online=float(m_on.get("VUS-ROC", 0.0)),
            vus_roc_static=float(m_st.get("VUS-ROC", 0.0)),
            vus_roc_batch=float(m_ba.get("VUS-ROC", 0.0)),
            auc_pr_online=float(m_on.get("AUC-PR", 0.0)),
            auc_pr_static=float(m_st.get("AUC-PR", 0.0)),
            auc_pr_batch=float(m_ba.get("AUC-PR", 0.0)),
            auc_roc_online=float(m_on.get("AUC-ROC", 0.0)),
            auc_roc_static=float(m_st.get("AUC-ROC", 0.0)),
            auc_roc_batch=float(m_ba.get("AUC-ROC", 0.0)),
            aff_f_online=float(m_on.get("Affiliation-F", 0.0)),
            aff_f_static=float(m_st.get("Affiliation-F", 0.0)),
            aff_f_batch=float(m_ba.get("Affiliation-F", 0.0)),
            sec_online=sec_on,
            sec_static=sec_st,
            recut_mismatch=recut_mismatch,
            sec_batch=sec_ba,
            error="",
        )
    except Exception as exc:
        return dict(collection=col, dataset=fname, error=f"{type(exc).__name__}: {exc}")


